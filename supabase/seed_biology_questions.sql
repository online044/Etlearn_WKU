-- 1. Create questions table matching the exact required schema
CREATE TABLE IF NOT EXISTS public.questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id INT DEFAULT 5,
    module_name TEXT NOT NULL DEFAULT 'General Biology',
    difficulty TEXT NOT NULL DEFAULT 'medium' CHECK (difficulty IN ('easy', 'medium', 'hard')),
    chapter TEXT NOT NULL,
    question TEXT NOT NULL,
    options JSONB NOT NULL,
    correct_answer TEXT NOT NULL,
    explanation TEXT,
    is_published BOOLEAN NOT NULL DEFAULT TRUE,
    is_pro BOOLEAN NOT NULL DEFAULT FALSE,
    -- Backward compatibility aliases
    subject TEXT GENERATED ALWAYS AS (module_name) STORED,
    unit TEXT GENERATED ALWAYS AS (chapter) STORED,
    course TEXT GENERATED ALWAYS AS (module_name) STORED,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

